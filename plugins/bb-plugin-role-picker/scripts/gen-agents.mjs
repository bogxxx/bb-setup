// Writes agents.generated.ts: the agent files role-picker spawns with, copied from
// this repo (claude/agents and cursor/agents). The server runs on another machine
// than the one these files live on, so it cannot read them from there; the copy
// ships with the plugin. sync.ps1 and sync.sh run this before they commit.
//   node plugins/bb-plugin-role-picker/scripts/gen-agents.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../../..");
const SOURCES = [
  ["claude/agents", ".claude/agents", ["explorer.md", "planner.md", "worker.md"]],
  ["cursor/agents", ".cursor/agents", ["cantrip-explore.md", "cantrip-implement.md", "cantrip-plan.md", "cantrip-review.md"]],
];

const entries = [];
for (const [fromDir, keyDir, files] of SOURCES) {
  for (const file of files) {
    const text = readFileSync(path.join(repo, fromDir, file), "utf8");
    entries.push(`  ${JSON.stringify(`${keyDir}/${file}`)}: ${JSON.stringify(text)},`);
  }
}

const out = [
  "// Generated by scripts/gen-agents.mjs from claude/agents and cursor/agents. Do not edit.",
  "export const SHIPPED_AGENTS: Record<string, string> = {",
  ...entries,
  "};",
  "",
].join("\n");
writeFileSync(path.join(here, "..", "agents.generated.ts"), out);
console.log(`agents.generated.ts: ${entries.length} agent files`);
